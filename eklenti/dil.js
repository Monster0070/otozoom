const M = METINLER[DIL];

// data-t: metin, data-t-html: sözlükteki biçimli metin, data-t-aria: aria-label
function dilUygula(kok = document) {
  document.documentElement.lang = DIL;
  kok.querySelectorAll("[data-t]").forEach((e) => (e.textContent = M[e.dataset.t]));
  kok.querySelectorAll("[data-t-html]").forEach((e) => (e.innerHTML = M[e.dataset.tHtml]));
  kok.querySelectorAll("[data-t-aria]").forEach((e) => e.setAttribute("aria-label", M[e.dataset.tAria]));
}
